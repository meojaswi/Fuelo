const PDFDocument = require("pdfkit");

/**
 * Streams a transaction receipt PDF directly to an HTTP response.
 * Kept simple/deterministic in v1 — same philosophy as messageBuilder:
 * no fancy templating engine, just a straightforward layout.
 */
function streamTransactionReceipt(res, { businessName, tx }) {
  const doc = new PDFDocument({ size: "A5", margin: 40 });
  doc.pipe(res);

  doc.fontSize(18).text(businessName, { align: "center" });
  doc.moveDown(0.5);
  doc
    .fontSize(10)
    .fillColor("#666")
    .text(tx.status === "voided" ? "Voided Transaction Receipt" : "Transaction Receipt", {
      align: "center",
    });
  doc.moveDown(1.5);

  doc.fillColor("#000").fontSize(11);
  doc.text(`Date: ${new Date(tx.createdAt).toLocaleString("en-IN")}`);
  doc.text(`Customer: ${tx.customerName}`);
  doc.text(`Phone: ${tx.customerPhone}`);
  doc.moveDown();

  if (tx.invoiceNumber) doc.text("Bill of Supply " + tx.invoiceNumber);
  if (tx.lineItems?.length) {
    for (const line of tx.lineItems)
      doc
        .fontSize(11)
        .text(
          `${line.itemType}: ${line.quantity} ${line.unit} (${line.pieces} pieces) - Rs. ${line.lineAmount.toFixed(2)}`
        );
    for (const charge of tx.charges) doc.text(`${charge.type}: Rs. ${charge.amount.toFixed(2)}`);
  } else doc.fontSize(12).text(`${tx.itemType}: ${tx.quantity} ${tx.unit}`);
  doc.text(`Amount: Rs. ${tx.amount}`);
  doc.text(`Payment Mode: ${tx.paymentMode.toUpperCase()}`);
  if (tx.upiReference) doc.text(`UPI Ref: ${tx.upiReference}`);
  if (tx.notes) doc.text(`Notes: ${tx.notes}`);

  doc.moveDown(2);
  doc.fontSize(9).fillColor("#999").text("Generated by Fuelo", { align: "center" });

  doc.end();
}

function streamTaxInvoice(res, tx, creditNote) {
  const { amountInWords, states } = require("../utils/gst");
  const { seller, recipient, tax, placeOfSupply, issuedAt } = tx.invoice;
  const sign = creditNote ? -1 : 1;
  const money = (value) => (value * sign).toFixed(2);
  const date = (value) => new Date(value).toLocaleDateString("en-IN", { timeZone: "Asia/Kolkata" });
  const doc = new PDFDocument({ size: "A4", margin: 36 });
  doc.pipe(res);
  doc.font("Helvetica-Bold").fontSize(17).text(seller.legalName);
  doc
    .font("Helvetica")
    .fontSize(10)
    .text(seller.address)
    .text("GSTIN " + seller.gstin);
  doc
    .moveDown()
    .font("Helvetica-Bold")
    .fontSize(14)
    .text(creditNote ? "Credit Note " + creditNote.number : "Tax Invoice " + tx.invoiceNumber);
  doc
    .font("Helvetica")
    .fontSize(10)
    .text("Issued " + date(creditNote?.issuedAt ?? issuedAt));
  if (creditNote)
    doc
      .text("Original invoice " + tx.invoiceNumber + " dated " + date(issuedAt))
      .text(creditNote.reason);
  if (tx.status === "voided" && !creditNote) doc.text("Voided by credit note");
  doc.moveDown().text("Bill to " + recipient.name + " | " + recipient.phone);
  if (recipient.address) doc.text(recipient.address);
  if (recipient.gstin) doc.text("GSTIN " + recipient.gstin);
  doc.text("Place of supply " + states[placeOfSupply] + " (" + placeOfSupply + ")").moveDown();
  const columns = [36, 160, 210, 290, 350, 412, 495, 558];
  function row(cells, heading = false) {
    const y = doc.y;
    doc.font(heading ? "Helvetica-Bold" : "Helvetica").fontSize(8);
    let height = 15;
    cells.forEach((cell, index) => {
      const width = columns[index + 1] - columns[index] - 4;
      const text = String(cell);
      height = Math.max(height, doc.heightOfString(text, { width }) + 5);
      doc.text(text, columns[index], y, { width, align: index > 2 ? "right" : "left" });
    });
    doc.x = 36;
    doc.y = y + height;
    doc
      .strokeColor("#aaa")
      .moveTo(36, doc.y - 2)
      .lineTo(558, doc.y - 2)
      .stroke();
  }
  const headers = [
    "Item / charge",
    "HSN",
    "Qty / unit",
    "Rate",
    "Taxable",
    "GST components",
    "Total",
  ];
  row(headers, true);
  for (const line of tax.rows) {
    if (doc.y > 715) {
      doc.addPage();
      row(headers, true);
    }
    const taxLabel =
      line.igst || placeOfSupply !== seller.state
        ? "IGST " + money(line.igst)
        : "CGST " + money(line.cgst) + "\nSGST " + money(line.sgst);
    row([
      line.itemType ?? line.type,
      line.hsnCode ?? "",
      line.kind === "item" ? `${line.quantity} ${line.unit}` : "",
      money(line.ratePerUnit ?? line.amount),
      money(line.taxableValue),
      taxLabel,
      money(line.total),
    ]);
  }
  if (doc.y > 610) doc.addPage();
  doc.moveDown().font("Helvetica").fontSize(10);
  doc.text("Taxable value Rs. " + money(tax.taxableValue));
  doc.text(
    "CGST Rs. " +
      money(tax.cgst) +
      " | SGST Rs. " +
      money(tax.sgst) +
      " | IGST Rs. " +
      money(tax.igst)
  );
  doc.text("Round off Rs. " + money(tax.roundOff));
  doc.font("Helvetica-Bold").text("Grand total Rs. " + money(tax.roundedTotal));
  doc.font("Helvetica").text(amountInWords(sign * tax.roundedTotal));
  if (!creditNote)
    doc.text(
      "Paid at sale Rs. " +
        (tx.paidAmount ?? 0).toFixed(2) +
        " | Initial credit Rs. " +
        (tx.creditAmount ?? 0).toFixed(2) +
        " | Customer credit used Rs. " +
        (tx.advanceApplied ?? 0).toFixed(2)
    );
  doc.moveDown().fontSize(9).text("Generated by Fuelo", { align: "center" });
  doc.end();
}

module.exports = { streamTransactionReceipt, streamTaxInvoice };
